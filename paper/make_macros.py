if not os.path.exists(fs_path):
    # FAIL CLOSED. figures_stats.json is generated by make_figures.py and gitignored; loading `{}`
    # in its absence would let every `if key in fs` block below silently skip its macros.
    raise SystemExit(f"FATAL: {fs_path} missing; run paper/make_figures.py first")
fs = _jload(fs_path)

L = []
def cmd(name, value):
    # Thousands separators must be {,} not ",": several macros are used inside $...$, where a bare
    # comma is math punctuation and typesets with a trailing space ("505, 479" in the abstract).
    # NaN/inf guard: a NaN in any source artifact would otherwise typeset as the literal "nan".
    if isinstance(value, float) and not math.isfinite(value):
        raise SystemExit(f"FATAL: macro {name} is {value!r}; a source artifact holds a non-finite value")
    if isinstance(value, str) and value.strip().lower() in ("nan", "inf", "-inf", "none"):
        raise SystemExit(f"FATAL: macro {name} formatted as {value!r}")
    L.append(r"\newcommand{\%s}{%s}" % (name, str(value).replace(",", "{,}")))

def pct(x):   return f"{100*x:.1f}"
def two(x):   return f"{x:.2f}"
def three(x): return f"{x:.3f}"

