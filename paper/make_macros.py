# Every artifact this generator reads goes through _jload, so `--list-inputs` can name them (each must be hashed in
# paper/results/MANIFEST.json; tests/test_validation_and_invariants.py checks it). --list-inputs writes nothing.
LIST_INPUTS = "--list-inputs" in sys.argv[1:]
INPUTS = []


def _jload(path):
    path = os.path.normpath(path)
    if path not in INPUTS:
        INPUTS.append(path)
    with open(path) as fh:
        return json.load(fh)



cn = _jload(os.path.join(HERE, "canonical_numbers.json"))
